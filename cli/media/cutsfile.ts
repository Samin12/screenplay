// cuts.yaml and review.md: reading, writing, and --accept parsing.
import fs from 'node:fs';
import YAML from 'yaml';
import { joinWords, truncate } from './text.ts';
import type { CutRange, Proposal, Word } from './types.ts';
import { fmtTime } from './util.ts';

export type CutsFile = {
  maxGap: number;
  cuts: CutRange[]; // regenerated by `screenplay cut`
  accepted: CutRange[]; // review proposals accepted with --accept (kept across reruns)
  manual: CutRange[]; // written by a person / the editing agent (kept across reruns)
  keep: CutRange[]; // never cut these words, whatever the lists above say
};

export const EMPTY_CUTS: CutsFile = { maxGap: 0.18, cuts: [], accepted: [], manual: [], keep: [] };

/** "s12" | 12 | "12" → 12 */
export function parseId(v: unknown): number {
  if (typeof v === 'number' && Number.isInteger(v)) return v;
  const m = /^s?(\d+)$/i.exec(String(v ?? '').trim());
  if (!m) throw new Error(`bad source word id "${String(v)}" (expected s<number>)`);
  return Number(m[1]);
}

function parseList(v: unknown, where: string): CutRange[] {
  if (v == null) return [];
  if (!Array.isArray(v)) throw new Error(`cuts.yaml: \`${where}\` must be a list`);
  return v.map((e: unknown, k) => {
    if (!e || typeof e !== 'object') throw new Error(`cuts.yaml: ${where}[${k}] must be {from, to, why}`);
    const r = e as { from?: unknown; to?: unknown; why?: unknown };
    const from = parseId(r.from);
    const to = r.to === undefined ? from : parseId(r.to);
    return { from: Math.min(from, to), to: Math.max(from, to), why: String(r.why ?? where) };
  });
}

export function parseCutsYaml(src: string): CutsFile {
  const doc = YAML.parse(src) as unknown;
  if (doc == null) return { ...EMPTY_CUTS };
  // A bare list (the format shown in EDIT-YAML.md) counts as hand-written cuts.
  if (Array.isArray(doc)) return { ...EMPTY_CUTS, manual: parseList(doc, 'manual') };
  if (typeof doc !== 'object') throw new Error('cuts.yaml must be a mapping or a list');
  const d = doc as Record<string, unknown>;
  const maxGap = d.maxGap === undefined ? EMPTY_CUTS.maxGap : Number(d.maxGap);
  if (!Number.isFinite(maxGap) || maxGap <= 0) throw new Error('cuts.yaml: maxGap must be a positive number of seconds');
  return { maxGap, cuts: parseList(d.cuts, 'cuts'), accepted: parseList(d.accepted, 'accepted'), manual: parseList(d.manual, 'manual'), keep: parseList(d.keep, 'keep') };
}

export function readCuts(file: string): CutsFile {
  if (!fs.existsSync(file)) return { ...EMPTY_CUTS };
  return parseCutsYaml(fs.readFileSync(file, 'utf8'));
}

/** Every range that removes words (cuts + accepted + manual). */
export function allCuts(c: CutsFile): CutRange[] {
  return [...c.cuts, ...c.accepted, ...c.manual];
}

function entry(r: CutRange, words: Word[]): string {
  const why = /^[\w -]+$/.test(r.why) ? r.why : JSON.stringify(r.why);
  const said = joinWords(words.slice(r.from, r.to + 1).map((w) => w.text));
  const at = words[r.from] ? ` [${fmtTime(words[r.from].start)}]` : '';
  return `  - {from: s${r.from}, to: s${r.to}, why: ${why}}  #${at} ${truncate(said, 90).replace(/\n/g, ' ')}`;
}

export function formatCutsYaml(c: CutsFile, words: Word[]): string {
  const list = (name: string, rs: CutRange[], help: string) =>
    `# ${help}\n${name}:${rs.length ? '\n' + rs.map((r) => entry(r, words)).join('\n') : ' []'}\n`;
  return [
    '# screenplay cut: source words to remove (inclusive ranges of ids from words.json).',
    '# `screenplay aroll` keeps everything else and trims every pause longer than maxGap seconds.',
    `maxGap: ${c.maxGap}`,
    '',
    list('cuts', c.cuts, 'Detected automatically. Regenerated by every `screenplay cut` run: put your own changes in manual/keep.'),
    list('accepted', c.accepted, 'Proposals from review.md accepted with `screenplay cut <work> --accept N`.'),
    list('manual', c.manual, 'Your own cuts: {from: s<i>, to: s<j>, why: ...}. Kept across reruns.'),
    list('keep', c.keep, 'Words that must stay even if a list above cuts them. Kept across reruns.'),
  ].join('\n');
}

/** "1,3,5-7" → [1,3,5,6,7] */
export function parseAccept(spec: string): number[] {
  const out = new Set<number>();
  for (const part of spec.split(',').map((s) => s.trim()).filter(Boolean)) {
    const m = /^(\d+)(?:\s*-\s*(\d+))?$/.exec(part);
    if (!m) throw new Error(`--accept: cannot read "${part}" (use e.g. 1,3,5-7)`);
    const a = Number(m[1]);
    const b = m[2] ? Number(m[2]) : a;
    for (let k = Math.min(a, b); k <= Math.max(a, b); k++) out.add(k);
  }
  return [...out].sort((x, y) => x - y);
}

function context(words: Word[], from: number, to: number, span = 8): string {
  const before = joinWords(words.slice(Math.max(0, from - span), from).map((w) => w.text));
  const cut = joinWords(words.slice(from, to + 1).map((w) => w.text));
  const after = joinWords(words.slice(to + 1, to + 1 + span).map((w) => w.text));
  return `${from > span ? '…' : ''}${before} ~~${cut}~~ ${after}${to + 1 + span < words.length ? '…' : ''}`.trim();
}

export function formatReview(work: string, words: Word[], ambiguous: Proposal[], confident: Proposal[], isAccepted: (p: Proposal) => boolean): string {
  const lines: string[] = [];
  lines.push('# Cut review', '');
  lines.push(`Ambiguous cut proposals for \`${work}\`. They are NOT applied yet.`);
  lines.push(`Accept the good ones with \`screenplay cut ${work} --accept 1,3,5-7\`, then run \`screenplay aroll ${work}\`.`);
  lines.push('Struck-through text (~~like this~~) is what the cut removes. Ids are source words (s<n>) from words.json.', '');
  if (!ambiguous.length) lines.push('_No ambiguous proposals._', '');
  ambiguous.forEach((p, k) => {
    const w0 = words[p.from];
    const w1 = words[p.to];
    const dur = w1.end - w0.start;
    lines.push(`## ${k + 1}. ${p.kind} s${p.from}–s${p.to} [${fmtTime(w0.start)}, ${dur.toFixed(1)} s]${isAccepted(p) ? ' (accepted)' : ''}`);
    lines.push('', `> ${context(words, p.from, p.to)}`, '', `Why: ${p.note ?? p.why}`, '');
  });
  lines.push('## Applied automatically', '');
  lines.push('These are already in cuts.yaml (`cuts:`). To undo one, add its range under `keep:` in cuts.yaml.', '');
  if (!confident.length) lines.push('_None._');
  for (const p of confident) {
    const w0 = words[p.from];
    lines.push(`- **${p.why}** s${p.from}–s${p.to} [${fmtTime(w0.start)}]: ${context(words, p.from, p.to, 5)}`);
  }
  lines.push('');
  return lines.join('\n');
}
